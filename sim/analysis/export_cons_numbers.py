# -*- coding: utf-8 -*-
"""Export conservative-model numbers used by the paper (2026-10-22 revision).

Reads the per-batch matrices, computes NetworkAware2 vs LeastLoad deltas, and writes:
  results/paper_numbers_cons.txt
  results/cons_summary_for_paper.md

Run from repo root:
  sim/.venv/Scripts/python.exe sim/analysis/export_cons_numbers.py
"""
from __future__ import annotations

import glob
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"

DIRS = {
    "synthetic": {
        "ideal": RES / "matrix_v2",
        "L": RES / "matrix_consL_synthetic",
        "P": RES / "matrix_consP_synthetic",
    },
    "azure": {
        "ideal": RES / "matrix_trace_v2",
        "L": RES / "matrix_consL_azure",
        "P": RES / "matrix_consP_azure",
    },
    "burstgpt": {
        "ideal": RES / "matrix_burstgpt_v2",
        "L": RES / "matrix_consL_burstgpt",
        "P": RES / "matrix_consP_burstgpt",
    },
}


def latest(d: Path, mode: str) -> Path:
    files = sorted(glob.glob(str(d / f"{mode}_*_runs.csv")))
    if not files:
        raise SystemExit(f"missing {mode} runs under {d}")
    return Path(files[-1])


def main_df(d: Path) -> pd.DataFrame:
    return pd.read_csv(latest(d, "main"))


def delta(df: pd.DataFrame, strat: str = "NetworkAware2") -> pd.DataFrame:
    sub = df[df.strategy.isin([strat, "LeastLoad"])]
    w = sub.pivot_table(
        index=["cell_id", "seed", "workload", "network", "staleness"],
        columns="strategy", values="sojourn_p95").reset_index()
    w["d"] = (w[strat] - w["LeastLoad"]) / w["LeastLoad"] * 100.0
    return w


def fmt(x: float) -> str:
    return "nan" if pd.isna(x) else f"{x:.1f}"


lines: list[str] = []
lines.append("# Conservative service-time model: numbers used in the paper")
lines.append("# generated by sim/analysis/export_cons_numbers.py")
lines.append("# delta p95 = (NetworkAware2 - LeastLoad) / LeastLoad * 100; negative is better")
lines.append("# ideal = matrix_*_v2; L = matrix_consL_<batch>; P = matrix_consP_<batch>")
lines.append("")

# ---- main table, 24 cells per model ----
lines.append("## MAIN (median over 4 workloads x 5 seeds; one row per batch/network/staleness/model)")
lines.append("tag,batch,network,staleness,model,dp95_pct,n_cells")
for batch, models in DIRS.items():
    for model, d in models.items():
        w = delta(main_df(d))
        g = w.groupby(["network", "staleness"]).agg(dp95=("d", "median"), n=("d", "size"))
        for (net, st), row in g.iterrows():
            tag = f"CONS.MAIN.{batch.upper()}.{net.upper()}.{st.upper()}.{model.upper()}"
            lines.append(f"{tag},{batch},{net},{st},{model},{fmt(row.dp95)},{int(row.n)}")
lines.append("")

# ---- degraded/fresh by workload ----
lines.append("## MAIN.DEGRADED.FRESH by workload")
lines.append("tag,batch,workload,model,dp95_pct")
for batch, models in DIRS.items():
    for model, d in models.items():
        w = delta(main_df(d))
        w = w[(w.network == "degraded") & (w.staleness == "fresh")]
        g = w.groupby("workload").d.median()
        for wl, val in g.items():
            tag = f"CONS.MAIN.{batch.upper()}.DEGRADED.FRESH.{wl.upper()}.{model.upper()}"
            lines.append(f"{tag},{batch},{wl},{model},{fmt(val)}")
lines.append("")

# ---- utilization ----
lines.append("## UTILIZATION (main matrix; mean and max of node_utilization)")
lines.append("tag,batch,model,util_mean,util_max")
for batch, models in DIRS.items():
    for model, d in models.items():
        df = main_df(d)
        tag = f"CONS.UTIL.{batch.upper()}.{model.upper()}"
        lines.append(f"{tag},{batch},{model},{df.node_utilization.mean():.3f},{df.node_utilization.max():.3f}")
lines.append("")

# ---- alignment ----
lines.append("## ALIGNMENT (align mode, degraded, median over 4 workloads x 5 seeds)")
lines.append("tag,batch,align,model,dp95_pct")
for batch, models in DIRS.items():
    for model, d in models.items():
        df = pd.read_csv(latest(d, "align"))
        sub = df[df.strategy.isin(["NetworkAware2", "LeastLoad"])]
        w = sub.pivot_table(
            index=["cell_id", "seed", "workload", "network", "align"],
            columns="strategy", values="sojourn_p95").reset_index()
        w["d"] = (w.NetworkAware2 - w.LeastLoad) / w.LeastLoad * 100.0
        w = w[w.network == "degraded"]
        g = w.groupby("align").d.median()
        for al, val in g.items():
            tag = f"CONS.ALIGN.{batch.upper()}.{al.upper()}.{model.upper()}"
            lines.append(f"{tag},{batch},{al},{model},{fmt(val)}")
lines.append("")

# ---- rho sweep ----
lines.append("## RHO SWEEP (rho mode, NetworkAware2, median over 4 workloads x 3 seeds)")
lines.append("tag,batch,network,target_rho,model,dp95_pct")
for batch, models in DIRS.items():
    for model, d in models.items():
        df = pd.read_csv(latest(d, "rho"))
        sub = df[df.strategy.isin(["NetworkAware2", "LeastLoad"])]
        w = sub.pivot_table(
            index=["cell_id", "seed", "workload", "network", "target_rho"],
            columns="strategy", values="sojourn_p95").reset_index()
        w["d"] = (w.NetworkAware2 - w.LeastLoad) / w.LeastLoad * 100.0
        g = w.groupby(["network", "target_rho"]).d.median()
        for (net, rho), val in g.items():
            tag = f"CONS.RHO.{batch.upper()}.{net.upper()}.{str(rho).replace('.', 'P')}.{model.upper()}"
            lines.append(f"{tag},{batch},{net},{rho},{model},{fmt(val)}")
lines.append("")

# ---- overall median and sign flips ----
lines.append("## OVERALL (120 paired cells; median delta p95 and sign flips vs ideal)")
lines.append("tag,batch,model,median_dp95_pct,sign_flips,n_cells")
for batch, models in DIRS.items():
    ideal = delta(main_df(models["ideal"]))
    ideal = ideal.groupby(["cell_id", "seed"]).d.median()
    for model in ("L", "P"):
        cur = delta(main_df(models[model]))
        cur = cur.groupby(["cell_id", "seed"]).d.median()
        cmp = pd.concat([ideal.rename("ideal"), cur.rename("cur")], axis=1).dropna()
        flips = int(((cmp.ideal < 0) != (cmp.cur < 0)).sum())
        tag = f"CONS.OVERALL.{batch.upper()}.{model}"
        lines.append(f"{tag},{batch},{model},{cmp.cur.median():.2f},{flips},{len(cmp)}")

(RES / "paper_numbers_cons.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

